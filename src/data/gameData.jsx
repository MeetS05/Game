// Get games by category
export const getGamesByCategory = (category) => {
  return gamesData.filter(game => game.category === category);
};

// Get featured games
export const getFeaturedGames = () => {
  return gamesData.filter(game => game.featured === true);
};

// Get trending games
export const getTrendingGames = () => {
  return gamesData.filter(game => game.trending === true);
};

// Get new games
export const getNewGames = () => {
  return gamesData.filter(game => game.new === true);
};

// Get popular games (rating >= 4.5)
export const getPopularGames = () => {
  return gamesData.filter(game => parseFloat(game.rating) >= 4.5);
};

// Get game by id
export const getGameById = (id) => {
  return gamesData.find(game => game.id === parseInt(id));
};

// Search games
export const searchGames = (query) => {
  return gamesData.filter(game =>
    game.title.toLowerCase().includes(query.toLowerCase()) ||
    game.category.toLowerCase().includes(query.toLowerCase()) ||
    game.tags.some(tag => tag.toLowerCase().includes(query.toLowerCase()))
  );
};